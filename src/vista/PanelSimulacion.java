    private void btnSimularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimularActionPerformed
        try {

        modeloTabla.setRowCount(0);
        jLabel5.setText("0 reservas");

        String textoFecha = txtFecha.getText().trim();

    if (textoFecha.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog( this, "Debe ingresar una fecha de referencia.");

        return;
    }

        java.time.LocalDate fecha =java.time.LocalDate.parse(textoFecha);

    if (!fecha.isAfter(java.time.LocalDate.now())) {

        javax.swing.JOptionPane.showMessageDialog(this, "La fecha de simulación debe ser futura.");

        return;
    }

        java.util.List<modelo.GestorHotel.ResumenReserva> reservas =controlador.simular(fecha);

    for (modelo.GestorHotel.ResumenReserva reserva : reservas) {

        modeloTabla.addRow(new Object[]{ reserva.getCodigo(), reserva.getFechaEntrada(),"Vencida" });
    }

    jLabel5.setText(reservas.size() + " reservas");

    if (reservas.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog( this,"No hay reservas que vencerían en esa fecha.");
    }

} catch (java.time.format.DateTimeParseException ex) {

        javax.swing.JOptionPane.showMessageDialog( this, "Fecha incorrecta. Utilice el formato AAAA-MM-DD.");

} catch (IllegalArgumentException ex) {

        javax.swing.JOptionPane.showMessageDialog( this, ex.getMessage());
}
    }//GEN-LAST:event_btnSimularActionPerformed

