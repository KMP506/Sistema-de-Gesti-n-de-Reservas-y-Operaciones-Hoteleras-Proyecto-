    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        try {

    String textoFecha = lblFecha.getText().trim();

    if (textoFecha.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog( this, "Debe ingresar una fecha.");

        return;
    }

    java.time.LocalDate fecha =java.time.LocalDate.parse(textoFecha);

    controlador.DisponibilidadControlador controlador =new controlador.DisponibilidadControlador();

    modelo.GestorHotel.ConsultaDisponibilidad resultado = controlador.consultar(fecha);

    jLabel4.setText( String.valueOf(resultado.getTotal()));

    if (resultado.getNumeros().isEmpty()) {

        txtResultado.setText( "No hay habitaciones disponibles para esta fecha.");

    } else {

        txtResultado.setText( "Fecha de consulta: " + resultado.getFecha() + "\n\nHabitaciones disponibles:\n" + String.join(", ", resultado.getNumeros()));
    }

} catch (java.time.format.DateTimeParseException ex) {

    javax.swing.JOptionPane.showMessageDialog( this, "Fecha incorrecta. Utilice el formato AAAA-MM-DD.");

} catch (IllegalArgumentException ex) {

    javax.swing.JOptionPane.showMessageDialog(
            this, ex.getMessage());
}
    }//GEN-LAST:event_btnConsultarActionPerformed


